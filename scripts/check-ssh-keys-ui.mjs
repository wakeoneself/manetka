import {chromium} from 'playwright-core'
import {preview} from 'vite'
import {mkdir} from 'node:fs/promises'
import assert from 'node:assert/strict'
const out='design/shots/ssh-keys';await mkdir(out,{recursive:true})
const server=await preview({preview:{host:'127.0.0.1',port:4173,strictPort:true}})
const browser=await chromium.launch({executablePath:'/Applications/Brave Browser.app/Contents/MacOS/Brave Browser',headless:true})
const page=await browser.newPage({viewport:{width:1320,height:860},deviceScaleFactor:2})
const errors=[];page.on('pageerror',e=>errors.push(e.message))
async function shot(name){await page.evaluate(()=>document.fonts.ready);await page.screenshot({path:`${out}/${name}.png`});assert.deepEqual(await page.evaluate(()=>[...document.querySelectorAll('button,input,td,th,h1,h2,pre')].filter(e=>{const r=e.getBoundingClientRect();return r.width>0&&r.height>0&&r.right>innerWidth+1}).map(e=>e.textContent?.slice(0,60))),[])}
try{
 await page.goto('http://127.0.0.1:4173/?demo=1')
 await page.getByRole('button',{name:/^SSH-ключи/}).click()
 await page.getByRole('heading',{name:'SSH-ключи',exact:true}).waitFor()
 assert.equal(await page.locator('tbody tr').count(),4)
 const used=page.locator('tbody tr').first();assert(await used.getByRole('button',{name:/Удалить ключ/}).isDisabled())
 assert(await page.locator('tbody tr').last().getByRole('button',{name:/Удалить ключ/}).isEnabled())
 await shot('01-list')
 await used.getByRole('button').first().click()
 assert(await page.getByRole('button',{name:'Удалить ключ',exact:true}).isDisabled())
 await shot('02-key-detail')
 await page.keyboard.press('Escape')
 await page.getByRole('button',{name:'Сгенерировать ключ',exact:true}).click()
 await page.getByLabel('Название ключа',{exact:true}).fill('Новый сервер')
 await shot('03-generate')
 await page.keyboard.press('Escape')
 await page.getByRole('button',{name:/^Серверы/}).click()
 await page.getByRole('button',{name:'Добавить сервер',exact:true}).click()
 await page.getByLabel('Название',{exact:true}).fill('Хельсинки')
 await page.getByRole('button',{name:'SSH-ключ',exact:true}).click()
 await shot('04-server-key')
 await page.getByLabel('SSH-ключ',{exact:true}).selectOption('__new')
 assert(await page.getByRole('button',{name:'Продолжить',exact:true}).isDisabled())
 await shot('05-server-generate')
 await page.setViewportSize({width:1024,height:700})
 await shot('06-compact')
 const box=await page.getByRole('dialog').boundingBox();assert(box.y>=0);assert(box.y+box.height<=700)
 await page.keyboard.press('Escape')
 await page.getByRole('button',{name:/^SSH-ключи/}).click()
 await page.getByRole('button',{name:'Светлая тема',exact:true}).click()
 await shot('07-light-compact')
 assert.deepEqual(errors,[])
 console.log('SSH keys UI passed: 7 frames, protected/free controls, generation wizard, dark/light, 1024×700.')
}finally{await browser.close();await new Promise(resolve=>server.httpServer.close(resolve))}
