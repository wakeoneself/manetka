// Regenerates electron/core/shim-bin.ts (gitignored; built locally and in CI): static linux binaries of the UDP shim (needs a local Go toolchain).
// Run after editing electron/core/shim.ts:  node --import tsx scripts/build-shim.mjs
import { spawnSync } from 'node:child_process'
import { createHash } from 'node:crypto'
import { existsSync, mkdtempSync, readFileSync, rmSync, writeFileSync } from 'node:fs'
import { tmpdir } from 'node:os'
import { join } from 'node:path'
import { gzipSync } from 'node:zlib'
import { shimGoMod, shimSource } from '../electron/core/shim.ts'

if (process.argv.includes('--if-missing') && existsSync(new URL('../electron/core/shim-bin.ts', import.meta.url))) process.exit(0)
const dir = mkdtempSync(join(tmpdir(), 'manetka-shim-build-'))
const out = {}
try {
  writeFileSync(join(dir, 'main.go'), shimSource); writeFileSync(join(dir, 'go.mod'), shimGoMod)
  for (const arch of ['amd64', 'arm64']) {
    const r = spawnSync('go', ['build', '-trimpath', '-ldflags=-s -w -buildid=', '-o', `shim-${arch}`, '.'], { cwd: dir, stdio: 'inherit', env: { ...process.env, CGO_ENABLED: '0', GOOS: 'linux', GOARCH: arch } })
    if (r.status !== 0) throw new Error('go build failed')
    const bin = readFileSync(join(dir, `shim-${arch}`))
    out[arch] = { sha256: createHash('sha256').update(bin).digest('hex'), gz: gzipSync(bin, { level: 9 }).toString('base64') }
  }
} finally { rmSync(dir, { recursive: true, force: true }) }
const sourceSha = createHash('sha256').update(shimSource + shimGoMod).digest('hex')
writeFileSync(new URL('../electron/core/shim-bin.ts', import.meta.url), `// Generated by scripts/build-shim.mjs from shim.ts. Do not edit.\nexport const shimSourceSha = '${sourceSha}'\nexport const shimBinaries: Record<'amd64' | 'arm64', { sha256: string; gz: string }> = ${JSON.stringify(out)}\n`)
console.log('ok', Object.fromEntries(Object.entries(out).map(([k, v]) => [k, v.sha256])))
